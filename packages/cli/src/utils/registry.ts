import { z } from "zod";

/**
 * Component registry schema.
 *
 * The registry is the canonical list of all components and their metadata.
 * It lives in packages/ui and is published so the CLI can resolve dependencies.
 */

export const registryItemSchema = z.object({
  name: z.string(),
  displayName: z.string(),
  description: z.string(),
  category: z.enum([
    "foundation",
    "form",
    "layout",
    "feedback",
    "overlay",
    "navigation",
    "display",
    "advanced",
  ]),
  /** Other Loony components this component depends on */
  dependencies: z.array(z.string()).default([]),
  /** npm packages required */
  npmDependencies: z.array(z.string()).default([]),
  /** Files that make up this component */
  files: z.array(z.string()),
  /** ARIA roles used */
  ariaRoles: z.array(z.string()).optional(),
  /** Status in the design system */
  status: z.enum(["stable", "beta", "experimental", "deprecated"]).default("stable"),
  /** Tailwind CSS version requirement */
  tailwindVersion: z.enum(["3", "4"]).default("4"),
});

