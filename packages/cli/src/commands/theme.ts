import * as p from "@clack/prompts";
import kleur from "kleur";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

interface ThemeOptions {
  preset?: string;
  out?: string;
}

const PRESETS = {
  default: {
    name: "Default",
    description: "The standard Loony theme with blue accent",
    accent: "oklch(0.546 0.245 262.881)",
    radius: "md",
  },
  minimal: {
    name: "Minimal",
    description: "Neutral palette with subtle styling",
    accent: "oklch(0.373 0.013 259.318)",
    radius: "sm",
  },
  rounded: {
    name: "Rounded",
    description: "Friendlier with more rounded corners",
    accent: "oklch(0.627 0.194 149.214)",
    radius: "lg",
  },
} as const;

type PresetKey = keyof typeof PRESETS;

function generateThemeCSS(customizations: {
  accentColor: string;
  radius: string;
}): string {
  return `/**
 * Loony Custom Theme
 * Generated by \`loony theme\`
 *
 * Override these variables in :root to customize your theme.
 * See https://loony.dev/docs/theming for the full token reference.
 */

@import "@loony/tokens/css";

@layer loony.tokens {
  :root {
    /* ---- Brand / Accent ---- */
    --loony-color-accent: ${customizations.accentColor};
    --loony-color-accent-hover: color-mix(in oklch, ${customizations.accentColor}, black 10%);
    --loony-color-accent-active: color-mix(in oklch, ${customizations.accentColor}, black 20%);
    --loony-color-accent-subtle: color-mix(in oklch, ${customizations.accentColor}, white 85%);
    --loony-color-accent-fg: oklch(1 0 0);

    /* ---- Focus ring matches accent ---- */
    --loony-color-ring: ${customizations.accentColor};

    /* ---- Radius personality ---- */
    --loony-radius-btn: var(--loony-radius-${customizations.radius});
    --loony-radius-input: var(--loony-radius-${customizations.radius});
    --loony-radius-card: var(--loony-radius-${customizations.radius === "sm" ? "md" : "lg"});
    --loony-radius-dialog: var(--loony-radius-${customizations.radius === "sm" ? "lg" : "xl"});
  }
}
`;
}

/**
 * loony theme — Interactively generate a custom theme CSS file.
 */
export async function theme(opts: ThemeOptions) {
  p.intro(kleur.bold().cyan("  loony theme  "));

  let selectedPreset: PresetKey;
  let accentColor: string;
  let radius: string;

  if (opts.preset && opts.preset in PRESETS) {
    selectedPreset = opts.preset as PresetKey;
  } else {
    const presetAnswer = await p.select({
      message: "Start from a preset:",
      options: Object.entries(PRESETS).map(([key, value]) => ({
        value: key,
        label: `${value.name} — ${value.description}`,
      })),
      initialValue: "default",
    });

    if (p.isCancel(presetAnswer)) {
      p.cancel("Cancelled.");
      process.exit(0);
    }

    selectedPreset = presetAnswer as PresetKey;
  }

  const preset = PRESETS[selectedPreset];

  const accentAnswer = await p.text({
    message: "Accent color (oklch, hex, or hsl):",
    placeholder: preset.accent,
    defaultValue: preset.accent,
  });

  if (p.isCancel(accentAnswer)) {
    p.cancel("Cancelled.");
    process.exit(0);
  }

  accentColor = accentAnswer ?? preset.accent;

  const radiusAnswer = await p.select({
    message: "Border radius personality:",
    options: [
      { value: "none", label: "None (sharp corners)" },
      { value: "xs", label: "Extra Small" },
      { value: "sm", label: "Small" },
      { value: "md", label: "Medium (default)" },
      { value: "lg", label: "Large (friendly)" },
      { value: "xl", label: "Extra Large" },
      { value: "full", label: "Full (pill-shaped)" },
    ],
    initialValue: preset.radius,
  });

  if (p.isCancel(radiusAnswer)) {
    p.cancel("Cancelled.");
    process.exit(0);
  }

  radius = radiusAnswer ?? preset.radius;

  const outPath = resolve(opts.out ?? "./src/styles/theme.css");
  const css = generateThemeCSS({ accentColor, radius });

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, css, "utf-8");

  p.log.success(`Theme written to ${outPath}`);

  p.note(
    [
      "Import your theme in your CSS entry point:",
      "",
      kleur.cyan(`  @import "./theme.css"; /* or relative path to your theme */`),
    ].join("\n"),
    "Usage",
  );

  p.outro(kleur.green("Theme generated."));
}
